import { CheckfuApi } from "@checkfu/api/Http/Api"
import type * as HttpApi from "effect/http-api/HttpApi"
import type * as HttpApiGroup from "effect/http-api/HttpApiGroup"
import * as OpenApi from "effect/http-api/OpenApi"

export const buildOpenApiJson = <Id extends string, Groups extends HttpApiGroup.Constraint>(
	api?: HttpApi.HttpApi<Id, Groups>,
): string =>
	`${JSON.stringify(api === undefined ? OpenApi.fromApi(CheckfuApi, {}) : OpenApi.fromApi(api, {}), null, 2)}\n`

export const exportDeterministicOpenApiJson = <
	Id extends string,
	Groups extends HttpApiGroup.Constraint,
>(
	api?: HttpApi.HttpApi<Id, Groups>,
): string => {
	const first = buildOpenApiJson(api)
	const second = buildOpenApiJson(api)
	if (first !== second) {
		throw new Error(
			"OpenApi.fromApi is non-deterministic: two consecutive exports produced different bytes.",
		)
	}
	return first
}

export const renderOpenApiModule = (openApiJson: string): string =>
	`// Code generated by @cloudflare/forge pipeline. DO NOT EDIT.\n\nexport const OPENAPI_DOCUMENT_JSON = ${JSON.stringify(openApiJson)}\n`
